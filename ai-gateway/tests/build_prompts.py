    for i, (prompt, pii) in enumerate(ROWS, 1):
        for v in pii:
            assert v in prompt, (i, v)
        f.write(json.dumps({"id": f"P{i:02d}", **BASE, "prompt": prompt, "pii": pii}, ensure_ascii=False) + "\n")
